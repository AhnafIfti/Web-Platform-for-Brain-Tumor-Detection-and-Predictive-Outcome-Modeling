from io import BytesIO
from xml.sax.saxutils import escape
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, Table, TableStyle, Image
from .visualization import representative_image, result_dir

DISCLAIMER = ('This software is intended for research and educational use only. Outputs are generated by an '
              'experimental machine-learning model and must not be interpreted as a medical diagnosis or used '
              'as the sole basis for patient-care decisions. Clinical interpretation should be performed by '
              'qualified healthcare professionals.')


def create_report(analysis):
    stream = BytesIO()
    doc = SimpleDocTemplate(stream, title='AI MRI Analysis Summary', author='NeuroVision AI',
                            leftMargin=44, rightMargin=44, topMargin=40, bottomMargin=40)
    styles = getSampleStyleSheet()
    styles.add(ParagraphStyle(name='Brand', fontName='Helvetica-Bold', fontSize=24, leading=30, textColor=colors.HexColor('#133b55')))
    overlay = BytesIO()
    representative_image(analysis).save(overlay, format='PNG')
    overlay.seek(0)
    elements = [Paragraph('NeuroVision AI', styles['Brand']),
                Paragraph('AI MRI Analysis Summary', styles['Heading2']), Spacer(1, 12),
                Paragraph(f'{analysis.display_id} | {analysis.created_at:%d %b %Y, %H:%M} UTC', styles['Normal']),
                Paragraph(f'Analysis UUID: {analysis.id}', styles['Normal']),
                Paragraph('Model: Swin-Tiny U-Net | Inputs: FLAIR + T1ce | Output: WT / TC / ET', styles['Normal']),
                Paragraph('Version: ' + escape(analysis.model_version), styles['Normal']),
                Paragraph(f'Slice {analysis.selected_slice + 1} of {analysis.number_of_slices} | Threshold: {analysis.threshold:.2f}', styles['Normal']),
                Spacer(1, 18),
                Table([[Image(str(result_dir(analysis.id) / f'{analysis.selected_slice}-original.png'), 224, 224),
                        Image(overlay, 224, 224)], ['Original FLAIR (model grid)', 'Segmentation overlay (65% opacity)']]),
                Spacer(1, 20)]
    rows = [['Region', 'Peak segmentation probability', 'Model-grid voxels']]
    for name, region in analysis.result_metadata['regions'].items():
        rows.append([name.upper(), f"{region['peak_probability']:.2%}", str(region['model_grid_voxels'])])
    table = Table(rows, colWidths=[90, 240, 150], hAlign='LEFT')
    table.setStyle(TableStyle([('BACKGROUND', (0, 0), (-1, 0), colors.HexColor('#e5f4f7')),
                               ('FONTNAME', (0, 0), (-1, 0), 'Helvetica-Bold'),
                               ('BOTTOMPADDING', (0, 0), (-1, -1), 10), ('TOPPADDING', (0, 0), (-1, -1), 10),
                               ('LINEBELOW', (0, 0), (-1, -1), .4, colors.HexColor('#d8e2e9'))]))
    elements += [table, Spacer(1, 12),
                 Paragraph('WT: cyan; TC: amber; ET: magenta. Regions overlap and are not additive. Probabilities are uncalibrated segmentation statistics, not diagnostic certainty. Counts use the resized model grid and are not physical tumor volumes.', styles['Normal']),
                 Spacer(1, 14), Paragraph('Experimental AI output', styles['Heading3']),
                 Paragraph(DISCLAIMER, styles['Normal']), Spacer(1, 10),
                 Paragraph('Checkpoint SHA-256: ' + analysis.result_metadata['checkpoint_sha256'], styles['Code'])]
    doc.build(elements)
    stream.seek(0)
    return stream
